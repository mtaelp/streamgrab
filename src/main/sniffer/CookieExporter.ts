import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import type { Session } from 'electron'
import { resolvePortablePaths } from '../portable/PortablePaths'

export class CookieExporter {
  public static async getCookieHeaderForUrl(session: Session, targetUrl: string): Promise<string> {
    try {
      const cleanUrl = targetUrl.startsWith('blob:') ? targetUrl.slice(5) : targetUrl
      const cookies = await session.cookies.get({ url: cleanUrl })
      if (!cookies || cookies.length === 0) return ''
      return cookies.map((c) => `${c.name}=${c.value}`).join('; ')
    } catch {
      return ''
    }
  }

  /**
   * Exports cookies from the given Electron session in standard Netscape cookies.txt format
   * so yt-dlp can authenticate seamlessly (including HttpOnly session & age-gate cookies).
   */
  public static async exportNetscapeCookieJar(
    session: Session,
    filterUrls?: string[]
  ): Promise<string> {
    const paths = resolvePortablePaths()
    const jarDir = path.join(paths.tempDir, 'cookies')
    fs.mkdirSync(jarDir, { recursive: true })
    const jarPath = path.join(jarDir, `cookies_${crypto.randomUUID()}.txt`)

    let allCookies: Electron.Cookie[] = []
    if (filterUrls && filterUrls.length > 0) {
      const seen = new Set<string>()
      for (const u of filterUrls) {
        try {
          const clean = u.startsWith('blob:') ? u.slice(5) : u
          const list = await session.cookies.get({ url: clean })
          for (const c of list) {
            const key = `${c.domain}|${c.path}|${c.name}`
            if (!seen.has(key)) {
              seen.add(key)
              allCookies.push(c)
            }
          }
        } catch {
          // ignore malformed URL
        }
      }
    } else {
      allCookies = await session.cookies.get({})
    }

    const lines = ['# Netscape HTTP Cookie File', '# Generated by StreamGrab Browser', '']
    for (const c of allCookies) {
      if (!c.domain || !c.name) continue
      const domain = c.hostOnly ? c.domain.replace(/^\./, '') : c.domain.startsWith('.') ? c.domain : `.${c.domain}`
      const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE'
      const cookiePath = c.path || '/'
      const secure = c.secure ? 'TRUE' : 'FALSE'
      const expiry = c.expirationDate ? Math.floor(c.expirationDate) : Math.floor(Date.now() / 1000) + 86400
      const value = (c.value ?? '').replace(/[\r\n\t]/g, '')
      lines.push([domain, includeSubdomains, cookiePath, secure, expiry, c.name, value].join('\t'))
    }

    await fs.promises.writeFile(jarPath, lines.join('\n'), 'utf8')
    return jarPath
  }
}
